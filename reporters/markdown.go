package reporters

import (
	"fmt"
	"io"
	"strings"

	"github.com/efekrbas/iso-guard/engine"
)

// MarkdownReporter generates an ISO/IEC 27001 compliance audit document in professional Markdown format.
type MarkdownReporter struct{}

// NewMarkdownReporter creates a new MarkdownReporter.
func NewMarkdownReporter() *MarkdownReporter {
	return &MarkdownReporter{}
}

func (m *MarkdownReporter) Report(report *engine.ScanReport, w io.Writer) error {
	sum := report.Summary

	// Compliance status badge
	statusText := "COMPLIANT (LOW RISK)"
	statusBadge := "🟢"
	if sum.ComplianceScore < 70.0 {
		statusText = "NON-COMPLIANT (HIGH RISK)"
		statusBadge = "🔴"
	} else if sum.ComplianceScore < 90.0 {
		statusText = "PARTIALLY COMPLIANT (MODERATE RISK)"
		statusBadge = "🟡"
	}

	fmt.Fprintf(w, "# ISO/IEC 27001:2022 Technical Security Controls Audit Report\n\n")
	fmt.Fprintf(w, "> **Confidential Audit Document** — Generated by `iso-guard` Automated Audit Engine\n\n")

	// Audit Metadata Table
	fmt.Fprintf(w, "### 📋 Audit Engagement Metadata\n\n")
	fmt.Fprintf(w, "| Attribute | Value |\n")
	fmt.Fprintf(w, "| :--- | :--- |\n")
	fmt.Fprintf(w, "| **Audit Target** | `%s` |\n", report.Target)
	fmt.Fprintf(w, "| **Standard / Profile** | `%s` (Annex A Technical & Organizational Controls) |\n", report.Profile)
	fmt.Fprintf(w, "| **Audit Execution Date** | `%s` |\n", report.Timestamp.Format("2006-01-02 15:04:05 UTC"))
	fmt.Fprintf(w, "| **Audit Duration** | `%s` |\n", sum.Duration.Round(100*1000))
	fmt.Fprintf(w, "| **Host Environment** | `%s / %s` (Host: `%s`) |\n", report.Environment.OS, report.Environment.Arch, report.Environment.Hostname)
	fmt.Fprintf(w, "| **Auditor Tool Version** | `%s` |\n", report.Environment.ToolVersion)
	fmt.Fprintf(w, "| **Overall Status** | %s **%s** |\n", statusBadge, statusText)
	fmt.Fprintf(w, "| **Compliance Score** | **%.1f%%** |\n", sum.ComplianceScore)
	fmt.Fprintf(w, "\n---\n\n")

	// Executive Summary
	fmt.Fprintf(w, "## 1. Executive Summary\n\n")
	fmt.Fprintf(w, "This audit evaluated the technical posture of target `%s` against applicable controls defined in **ISO/IEC 27001:2022 Annex A**.\n\n", report.Target)

	fmt.Fprintf(w, "### Key Performance & Compliance Indicators (KPIs)\n\n")
	fmt.Fprintf(w, "| Metric | Count | Percentage |\n")
	fmt.Fprintf(w, "| :--- | :---: | :---: |\n")

	total := sum.TotalRules
	calcPct := func(count int) string {
		if total == 0 {
			return "0.0%"
		}
		return fmt.Sprintf("%.1f%%", float64(count)/float64(total)*100.0)
	}

	fmt.Fprintf(w, "| **Total Controls Evaluated** | **%d** | 100.0%% |\n", total)
	fmt.Fprintf(w, "| ✅ **Passed Controls** | **%d** | %s |\n", sum.Passed, calcPct(sum.Passed))
	fmt.Fprintf(w, "| ❌ **Failed Controls (Violations)** | **%d** | %s |\n", sum.Failed, calcPct(sum.Failed))
	fmt.Fprintf(w, "| ⚠️ **Warnings / Observations** | **%d** | %s |\n", sum.Warnings, calcPct(sum.Warnings))
	fmt.Fprintf(w, "| ⚪ **Skipped / Not Applicable** | **%d** | %s |\n", sum.Skipped, calcPct(sum.Skipped))
	fmt.Fprintf(w, "\n")

	fmt.Fprintf(w, "### Findings by Risk Severity\n\n")
	fmt.Fprintf(w, "| Critical | High | Medium | Low |\n")
	fmt.Fprintf(w, "| :---: | :---: | :---: | :---: |\n")
	fmt.Fprintf(w, "| 🚨 **%d** | 🔴 **%d** | 🟡 **%d** | 🔵 **%d** |\n",
		sum.CriticalCount, sum.HighCount, sum.MediumCount, sum.LowCount)
	fmt.Fprintf(w, "\n---\n\n")

	// Detailed Control Findings Matrix
	fmt.Fprintf(w, "## 2. Controls Evaluation Matrix\n\n")
	fmt.Fprintf(w, "| Status | ISO Control | Rule Identifier | Severity | Category | Remediation Guidance |\n")
	fmt.Fprintf(w, "| :---: | :--- | :--- | :---: | :--- | :--- |\n")

	for _, res := range report.Results {
		statusIcon := "✅ PASS"
		if res.Status == engine.StatusFail {
			statusIcon = "❌ FAIL"
		} else if res.Status == engine.StatusWarn {
			statusIcon = "⚠️ WARN"
		} else if res.Status == engine.StatusSkip {
			statusIcon = "⚪ SKIP"
		}

		remed := res.Remediation
		if remed == "" {
			remed = "N/A (Control passed)"
		} else if len(remed) > 80 {
			remed = remed[:77] + "..."
		}
		remed = strings.ReplaceAll(remed, "|", "\\|")

		fmt.Fprintf(w, "| %s | **%s** | `%s` | `%s` | %s | %s |\n",
			statusIcon, res.ControlID, res.RuleID, res.Severity, res.Category, remed)
	}

	fmt.Fprintf(w, "\n---\n\n")

	// Section 3: Remediation & Action Plan for Non-Compliant Items
	fmt.Fprintf(w, "## 3. Remediation Action Plan (Düzeltme ve İyileştirme Planı)\n\n")

	hasActionItems := false
	for _, res := range report.Results {
		if res.Status == engine.StatusPass || res.Status == engine.StatusSkip {
			continue
		}
		hasActionItems = true

		statusBadge := "❌ NON-COMPLIANT (FAIL)"
		if res.Status == engine.StatusWarn {
			statusBadge = "⚠️ OBSERVATION / WARNING"
		}

		fmt.Fprintf(w, "### [%s] %s — %s\n\n", res.ControlID, res.Title, statusBadge)
		fmt.Fprintf(w, "- **Control Clause**: `ISO/IEC 27001 Annex %s`\n", res.ControlID)
		fmt.Fprintf(w, "- **Rule ID**: `%s`\n", res.RuleID)
		fmt.Fprintf(w, "- **Category**: %s\n", res.Category)
		fmt.Fprintf(w, "- **Risk Severity**: `%s`\n", res.Severity)
		fmt.Fprintf(w, "- **Audit Finding**: %s\n", res.Message)

		if res.Remediation != "" {
			fmt.Fprintf(w, "\n#### 🛠️ Recommended Remediation Steps (Düzeltme Adımları):\n")
			fmt.Fprintf(w, "> %s\n\n", res.Remediation)
		}

		if len(res.Details) > 0 {
			fmt.Fprintf(w, "#### 🔍 Evidence / Finding Details:\n")
			for k, v := range res.Details {
				fmt.Fprintf(w, "- **%s**:\n", k)
				if list, ok := v.([]string); ok {
					for _, item := range list {
						fmt.Fprintf(w, "  - `%s`\n", item)
					}
				} else if listInterface, ok := v.([]interface{}); ok {
					for _, item := range listInterface {
						fmt.Fprintf(w, "  - `%v`\n", item)
					}
				} else {
					fmt.Fprintf(w, "  - `%v`\n", v)
				}
			}
			fmt.Fprintf(w, "\n")
		}
		fmt.Fprintf(w, "---\n\n")
	}

	if !hasActionItems {
		fmt.Fprintf(w, "🎉 **Congratulations!** All active ISO/IEC 27001 controls passed without any findings or warnings.\n\n")
	}

	// Auditor Sign-off Block
	fmt.Fprintf(w, "## 4. Auditor Sign-Off & Verification\n\n")
	fmt.Fprintf(w, "| Field | Lead Auditor Sign-Off |\n")
	fmt.Fprintf(w, "| :--- | :--- |\n")
	fmt.Fprintf(w, "| **Auditor Name / Role** | Certified Information Security Auditor (CISA / ISO 27001 Lead Auditor) |\n")
	fmt.Fprintf(w, "| **Audit Signature** | ____________________________________ |\n")
	fmt.Fprintf(w, "| **Verification Date** | `%s` |\n\n", report.Timestamp.Format("2006-01-02"))

	return nil
}

var _ Reporter = (*MarkdownReporter)(nil)
